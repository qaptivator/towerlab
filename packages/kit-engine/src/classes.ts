/** True when `className` is `base` or inherits from it. Every class is an Instance. */
export function isA(className: string, base: string): boolean {
  if (base === "Instance") return true;
  const seen = new Set<string>();
  let current: string | undefined = className;
  while (current && !seen.has(current)) {
    if (current === base) return true;
    seen.add(current);
    current = CLASS_PARENT[current];
  }
  return false;
}

export function isBasePart(className: string): boolean {
  return isA(className, "BasePart");
}
